package arrays;

/*
 * Program: PrintArray
 * Module: Arrays
 * Purpose: Stores and prints elements of an integer array.
 */

public class PrintArray {

    public static void main(String[] args) {

        int[] numbers = {10, 20, 30, 40, 50};

        for (int i = 0; i < numbers.length; i++) {
            System.out.println(numbers[i]);
        }

    }

}