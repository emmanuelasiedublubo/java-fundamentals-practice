public class PerimeterCalculator {

    public static void main(String[] args) {

        int length = 12;
        int width = 6;

        int perimeter = 2 * (length + width);

        System.out.println("Length: " + length);
        System.out.println("Width: " + width);
        System.out.println("Perimeter: " + perimeter);
    }
}