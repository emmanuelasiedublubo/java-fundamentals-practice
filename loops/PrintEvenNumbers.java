package loops;

/*
 * Program: PrintEvenNumbers
 * Module: Loops
 * Purpose: Prints all even numbers from 2 to 20 using a for loop.
 */

public class PrintEvenNumbers {

    public static void main(String[] args) {

        for (int i = 2; i <= 20; i += 2) {
            System.out.println(i);
        }

    }

}