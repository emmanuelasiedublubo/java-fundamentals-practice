package loops;

/*
 * Program: PrintOddNumbers
 * Module: Loops
 * Purpose: Prints all odd numbers from 1 to 19 using a for loop.
 */

public class PrintOddNumbers {

    public static void main(String[] args) {

        for (int i = 1; i <= 20; i += 2) {
            System.out.println(i);
        }

    }

}