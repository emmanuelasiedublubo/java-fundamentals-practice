package loops;

/*
 * Program: PrintNumbers1To10
 * Module: Loops
 * Purpose: Prints the numbers 1 to 10 using a for loop.
 */

public class PrintNumbers1To10 {

    public static void main(String[] args) {

        for (int i = 1; i <= 10; i++) {
            System.out.println(i);
        }

    }

}
