package loops;

/*
 * Program: PrintNumbers10To1
 * Module: Loops
 * Purpose: Prints the numbers 10 to 1 using a for loop.
 */

public class PrintNumbers10To1 {

    public static void main(String[] args) {

        for (int i = 10; i >= 1; i--) {
            System.out.println(i);
        }

    }

}